"""Reproducible trusted outline font subset for ESP32 and the offline browser."""
from pathlib import Path
import argparse,base64,hashlib,json
from fontTools.ttLib import TTFont
from fontTools import subset
from io import BytesIO
root=Path(__file__).resolve().parents[2];p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
folder=root/'lib/meter_numerals';source=(folder/'assets/RobotoMono-Medium.ttf').read_bytes()
assert hashlib.sha256(source).hexdigest()=='4acbb2725a260eafff1bcaade3501204ca774e56346e259ee1b61d56996d2611'
font=TTFont(BytesIO(source),recalcTimestamp=False);options=subset.Options();options.hinting=False
chars='0123456789.+- OLVREe';sub=subset.Subsetter(options=options);sub.populate(text=chars);sub.subset(font)
for name_id in (1,3,4,6):font['name'].setName('MeterDigits' if name_id==6 else 'Meter Digits',name_id,3,1,0x409)
assert 'glyf' in font and not any(t in font for t in ('EBDT','CBDT','sbix'))
out=BytesIO();font.save(out);data=out.getvalue();digest=hashlib.sha256(data).hexdigest()
lines=['// Generated by build_meter_numerals.py; Roboto Mono derivative, see assets/OFL.txt.','#pragma once',f'#define METER_NUMERAL_FONT_SHA "{digest}"','static const unsigned char METER_NUMERAL_FONT[]={']
for i in range(0,len(data),20):lines.append(','.join(str(b) for b in data[i:i+20])+',')
lines+=['};',f'static const unsigned METER_NUMERAL_FONT_BYTES={len(data)};','']
header='\n'.join(lines)
css='/* BEGIN GENERATED METER NUMERALS */\n@font-face{font-family:MeterDigits;src:url(data:font/ttf;base64,'+base64.b64encode(data).decode()+') format("truetype");font-weight:500;font-display:block}\n/* END GENERATED METER NUMERALS */\n'
style=root/'src/esp32_touch/meter/web/style.css';existing=style.read_text(encoding='utf-8')
if existing.startswith('/* BEGIN GENERATED METER NUMERALS */'):existing=existing.split('/* END GENERATED METER NUMERALS */\n',1)[1]
targets={folder/'src/meter_numeral_font.h':header,style:css+existing}
for path,text in targets.items():
    if args.check:assert path.read_text(encoding='utf-8')==text,'Stale numeral asset: '+str(path)
    else:path.write_text(text,encoding='utf-8',newline='\n')
meta={'source_sha256':hashlib.sha256(source).hexdigest(),'subset_sha256':digest,'subset_bytes':len(data),'glyphs':len(font.getGlyphOrder()),'outline_only':True}
if not args.check:(folder/'assets/font-manifest.json').write_text(json.dumps(meta,indent=2)+'\n')
print(json.dumps(meta))
