"""Emit native cases from the JSON vectors also read directly by Node."""
from pathlib import Path
import argparse,json
root=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
cases=json.loads((root/'test/fixtures/meter_value_format.json').read_text())
lines=['// Generated by build_meter_value_fixtures.py. Do not edit.',
       'struct FormatCase {const char *name;double value;meter_ui::NumberFormat format;bool available;meter_ui::NumberState state;const char *cells;unsigned decimal;};',
       'static const FormatCase formatCases[]={']
states={'numeric':'Numeric','overflow':'Overflow','unavailable':'Unavailable','invalid':'Invalid'}
for c in cases:
    fmt=c['format'];kind=c.get('kind')
    value={'nan':'std::numeric_limits<double>::quiet_NaN()','infinity':'std::numeric_limits<double>::infinity()','missing':'0'}.get(kind,repr(c.get('value',0)))
    pad={'blank':'Blank','zero':'Zero'}.get(fmt['padding'],'Invalid')
    lines.append('{%s,%s,{%s,%s,meter_ui::Padding::%s},%s,meter_ui::NumberState::%s,%s,%s},'%(json.dumps(c['name']),value,fmt['digits'],fmt['decimals'],pad,'false' if kind=='missing' else 'true',states[c['state']],json.dumps(c['cells']),c['decimalIndex']))
lines.append('};\n');content='\n'.join(lines)
target=root/'test/test_meter_value_format/fixtures.inc';target.parent.mkdir(parents=True,exist_ok=True)
if args.check:assert target.read_text()==content,'Native format fixtures are stale'
else:target.write_text(content)
print('Shared format fixtures:',len(cases),'cases')
