"""Deterministically embed the offline meter dashboard in the ESP32 image.

Run from any directory: python tools/esp32/build_meter_web.py
No build-time packages, network requests or minifier are required.
"""
from pathlib import Path
import argparse


def build(root: Path) -> str:
    web = root / "src/esp32_touch/meter/web"
    html = (web / "index.html").read_text(encoding="utf-8")
    for marker, filename in (("/* METER_CSS */", "style.css"), ("/* METER_CALC_CSS */", "calculations.css"),
                             ("/* METER_CARD_CSS */", "card.css"), ("/* METER_CARD_UI */", "card_ui.js"),
                             ("/* METER_CORE */", "core.js"), ("/* METER_CALCULATIONS */", "calculations.js"),
                             ("/* METER_CALC_UI */", "calculations_ui.js"), ("/* METER_VALUE_FORMAT */", "value_format.js"),
                             ("/* METER_VALUE_TILES */", "value_tiles.js"), ("/* METER_APP */", "app.js")):
        asset = (web / filename).read_text(encoding="utf-8").replace("\r\n", "\n")
        if html.count(marker) != 1:
            raise ValueError(f"Expected exactly one {marker} placeholder")
        html = html.replace(marker, asset.rstrip())
    delimiter = "METERWEB"
    if f'){delimiter}"' in html:
        raise ValueError("C++ raw string delimiter occurs in asset")
    return "// Generated by tools/esp32/build_meter_web.py. Do not edit.\n#pragma once\n#include <pgmspace.h>\n\nstatic const char METER_WEB_HTML[] PROGMEM = R\"" + delimiter + "(" + html.rstrip() + ")" + delimiter + '\";\n'


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated header is stale")
    args = parser.parse_args()
    repository = Path(__file__).resolve().parents[2]
    output = repository / "src/esp32_touch/meter/meter_web_assets.h"
    content = build(repository)
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != content:
            raise SystemExit("meter_web_assets.h is stale; run tools/esp32/build_meter_web.py")
        print(f"Current: {output} ({len(content.encode('utf-8'))} bytes)")
    else:
        output.write_text(content, encoding="utf-8", newline="\n")
        print(f"Generated: {output} ({len(content.encode('utf-8'))} bytes)")
